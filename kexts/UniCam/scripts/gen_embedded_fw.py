#!/usr/bin/env python3
"""
gen_embedded_fw.py
Compress Intel IPU4P firmware binary (cpd_component_signed.bin) with zlib -9
and emit a C++ source file for Pure-EFI in-kernel embedding inside UniCamIPU.kext.
"""
import os
import struct
import sys
import zlib


CPD_HDR_MARK = 0x44504324  # "$CPD"


def main() -> int:
    if len(sys.argv) != 3:
        print(f"Usage: {sys.argv[0]} <input_cpd.bin> <output_cpp>", file=sys.stderr)
        return 2

    in_path = sys.argv[1]
    out_path = sys.argv[2]

    with open(in_path, "rb") as f:
        raw = f.read()

    if len(raw) < 16:
        print(f"[!] Firmware file too small: {in_path}", file=sys.stderr)
        return 1

    hdr_mark = struct.unpack_from("<I", raw, 0)[0]
    if hdr_mark != CPD_HDR_MARK:
        print(f"[!] Invalid $CPD header mark 0x{hdr_mark:08x} in {in_path}", file=sys.stderr)
        return 1

    comp = zlib.compress(raw, 9)
    os.makedirs(os.path.dirname(os.path.abspath(out_path)), exist_ok=True)

    with open(out_path, "w", encoding="utf-8") as f:
        f.write("// Auto-generated by kexts/UniCam/scripts/gen_embedded_fw.py — DO NOT EDIT\n")
        f.write("#include <stdint.h>\n\n")
        f.write("namespace ipu4p {\n\n")
        f.write(f"extern const uint32_t gEmbeddedIpu4pFwRawSize = {len(raw)}U;\n")
        f.write(f"extern const uint32_t gEmbeddedIpu4pFwZlibSize = {len(comp)}U;\n")
        f.write("extern const uint8_t gEmbeddedIpu4pFwZlib[] = {\n")
        for off in range(0, len(comp), 16):
            chunk = comp[off:off + 16]
            line = ", ".join(f"0x{b:02x}" for b in chunk)
            f.write(f"    {line},\n")
        f.write("};\n\n")
        f.write("} // namespace ipu4p\n")

    print(f"[+] Embedded IPU4P FW: {len(raw)} bytes -> zlib {len(comp)} bytes ({100.0 * len(comp) / len(raw):.1f}%)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
