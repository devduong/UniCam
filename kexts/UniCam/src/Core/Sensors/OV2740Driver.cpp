OV2740Driver::OV2740Driver()
    : csiLanes_(2U),
      linkFreqHz_(360000000ULL),
      activeVts_(kVts360Mhz) {
}

bool OV2740Driver::use180Mhz_() const {
    return (linkFreqHz_ != 0ULL && linkFreqHz_ <= 200000000ULL) || (csiLanes_ == 1U);
}

void OV2740Driver::setBusConfig(uint32_t csiLanes, uint64_t linkFreqHz) {
    csiLanes_ = (csiLanes == 1U) ? 1U : 2U;
    if (linkFreqHz != 0ULL) {
        linkFreqHz_ = linkFreqHz;
    } else {
        linkFreqHz_ = (csiLanes_ == 1U) ? 180000000ULL : 360000000ULL;
    }
    activeVts_ = use180Mhz_() ? kVts180Mhz : kVts360Mhz;
}

UniCamSensorModeDesc OV2740Driver::defaultMode() const {
    const bool mode180 = use180Mhz_();
    UniCamSensorModeDesc mode;
    mode.width = kWidth;
    mode.height = kHeight;
    mode.bpp = 10;
    mode.hts = kHts;
    mode.vts = mode180 ? kVts180Mhz : kVts360Mhz;
    mode.linkFreqHz = mode180 ? 180000000ULL : 360000000ULL;
    mode.sclkHz = 72000000ULL;
    mode.bayerOrder = 1U; /* SGRBG10 */
    return mode;
}

IOReturn OV2740Driver::identify(II2CTransport *i2c, uint32_t *outChipId, uint8_t rawBytes[4]) {
    if (!i2c || !outChipId) {
        return kIOReturnBadArgument;
    }
    uint8_t buf[3] = {0, 0, 0};
    uint32_t chipId = 0;
    const IOReturn ret = i2c->readReg24(kRegChipId, &chipId, buf);
    if (rawBytes) {
        rawBytes[0] = buf[0];
        rawBytes[1] = buf[1];
        rawBytes[2] = buf[2];
        rawBytes[3] = 0;
    }
    if (ret != kIOReturnSuccess) {
        return ret;
    }
    *outChipId = chipId;
    return (chipId == UNICAM_OV2740_CHIP_ID) ? kIOReturnSuccess : kIOReturnNotFound;
}

IOReturn OV2740Driver::configureMode(II2CTransport *i2c, uint32_t modeIndex, uint32_t testPattern) {
    if (!i2c) {
        return kIOReturnBadArgument;
    }
    if (modeIndex != 0) {
        return kIOReturnUnsupported;
    }

    IOReturn ret = i2c->writeReg8(kRegSwReset, 0x01);
    if (ret != kIOReturnSuccess) {
        return ret;
    }
    IOSleep(12);

    const bool mode180 = use180Mhz_();
    activeVts_ = mode180 ? kVts180Mhz : kVts360Mhz;

    const UniCamSensorRegVal8 *pllTbl = mode180 ? kMipiDataRate360Mbps : kMipiDataRate720Mbps;
    const size_t pllCnt = mode180
        ? (sizeof(kMipiDataRate360Mbps) / sizeof(kMipiDataRate360Mbps[0]))
        : (sizeof(kMipiDataRate720Mbps) / sizeof(kMipiDataRate720Mbps[0]));
    if ((ret = unicamWriteRegTable8(i2c, "OV2740", pllTbl, pllCnt, 0, 0)) != kIOReturnSuccess) {
        return ret;
    }

    const UniCamSensorRegVal8 *modeTbl = mode180 ? kMode1932x1092Regs180Mhz : kMode1932x1092Regs360Mhz;
    const size_t modeCnt = mode180
        ? (sizeof(kMode1932x1092Regs180Mhz) / sizeof(kMode1932x1092Regs180Mhz[0]))
        : (sizeof(kMode1932x1092Regs360Mhz) / sizeof(kMode1932x1092Regs360Mhz[0]));
    if ((ret = unicamWriteRegTable8(i2c, "OV2740", modeTbl, modeCnt, 0, 0)) != kIOReturnSuccess) {
        return ret;
    }

    if (csiLanes_ == 1U) {
        if ((ret = i2c->writeReg8(kRegMipiLaneCtrl, 0x12)) != kIOReturnSuccess) {
            return ret;
        }
    }

    if ((ret = i2c->writeReg16(kRegVts, static_cast<uint16_t>(activeVts_))) != kIOReturnSuccess) {
        return ret;
    }

    const uint8_t patVal = testPattern
        ? static_cast<uint8_t>((((testPattern - 1U) & 0x03U) << 2) | 0x80U)
        : 0x00U;
    if ((ret = i2c->writeReg8(kRegTestPattern, patVal)) != kIOReturnSuccess) {
        return ret;
    }

    return setExposureAndGain(i2c, activeVts_ - kExposureMargin, 256U, kDigitalGainMin);
}

IOReturn OV2740Driver::setStreaming(II2CTransport *i2c, bool enable) {
    if (!i2c) {
        return kIOReturnBadArgument;
    }
    return i2c->writeReg8(kRegModeSelect, enable ? 0x01 : 0x00);
}

IOReturn OV2740Driver::setExposureAndGain(II2CTransport *i2c,
                                          uint32_t exposureLines,
                                          uint32_t analogGain,
                                          uint32_t digitalGain) {
    if (!i2c) {
        return kIOReturnBadArgument;
    }

    const uint32_t vts = activeVts_ ? activeVts_ : kVts360Mhz;
    const uint32_t exp = unicamClampU32(exposureLines, kExposureMin, vts - kExposureMargin);
    // SoftISP uses Q8 analogGain (256 = 1.0x); OV2740 uses Q7 (128 = 1.0x).
    const uint32_t scaledAnalog = (analogGain >= 256U) ? (analogGain >> 1) : analogGain;
    const uint16_t aGain = static_cast<uint16_t>(
        unicamClampU32(scaledAnalog, kAnalogGainMin, kAnalogGainMax));
    const uint16_t dGain = static_cast<uint16_t>(
        unicamClampU32(digitalGain < kDigitalGainMin ? kDigitalGainMin : digitalGain,
                       kDigitalGainMin, kDigitalGainMax));

    IOReturn ret = i2c->writeReg24(kRegExposure, (exp << 4) & 0x0FFFF0U);
    if (ret != kIOReturnSuccess) return ret;

    ret = i2c->writeReg16(kRegAnalogGain, aGain);
    if (ret != kIOReturnSuccess) return ret;

    if ((ret = i2c->writeReg8(kRegGroupAccess, 0x00)) != kIOReturnSuccess) return ret;
    if ((ret = i2c->writeReg16(kRegMwbRGain, dGain)) != kIOReturnSuccess) return ret;
    if ((ret = i2c->writeReg16(kRegMwbGGain, dGain)) != kIOReturnSuccess) return ret;
    if ((ret = i2c->writeReg16(kRegMwbBGain, dGain)) != kIOReturnSuccess) return ret;
    if ((ret = i2c->writeReg8(kRegGroupAccess, 0x10)) != kIOReturnSuccess) return ret;
    return i2c->writeReg8(kRegGroupAccess, 0xA0);
}
