OV02C10Driver::OV02C10Driver()
    : csiLanes_(2U),
      activeVts_(kVtsMin * 2U) {
}

void OV02C10Driver::setBusConfig(uint32_t csiLanes, uint64_t linkFreqHz) {
    (void)linkFreqHz;
    csiLanes_ = (csiLanes == 1U) ? 1U : 2U;
    activeVts_ = kVtsMin * csiLanes_;
}

UniCamSensorModeDesc OV02C10Driver::defaultMode() const {
    UniCamSensorModeDesc mode;
    mode.width = kWidth;
    mode.height = kHeight;
    mode.bpp = 10;
    mode.hts = kHts;
    mode.vts = kVtsMin * csiLanes_;
    mode.linkFreqHz = 400000000ULL;
    mode.sclkHz = 80000000ULL;
    mode.bayerOrder = 1U; /* SGRBG10 */
    return mode;
}

IOReturn OV02C10Driver::identify(II2CTransport *i2c, uint32_t *outChipId, uint8_t rawBytes[4]) {
    if (!i2c || !outChipId) {
        return kIOReturnBadArgument;
    }
    uint8_t buf[3] = {0, 0, 0};
    uint32_t chipId = 0;
    const IOReturn ret = i2c->readReg24(kRegChipId, &chipId, buf);
    if (rawBytes) {
        rawBytes[0] = buf[0];
        rawBytes[1] = buf[1];
        rawBytes[2] = buf[2];
        rawBytes[3] = 0;
    }
    if (ret != kIOReturnSuccess) {
        return ret;
    }
    *outChipId = chipId;
    return (chipId == UNICAM_OV02C10_CHIP_ID) ? kIOReturnSuccess : kIOReturnNotFound;
}

IOReturn OV02C10Driver::configureMode(II2CTransport *i2c, uint32_t modeIndex, uint32_t testPattern) {
    if (!i2c) {
        return kIOReturnBadArgument;
    }
    if (modeIndex != 0) {
        return kIOReturnUnsupported;
    }

    activeVts_ = kVtsMin * csiLanes_;

    IOReturn ret = unicamWriteRegTable8(
        i2c, "OV02C10", kOv02c10BaseSetting,
        sizeof(kOv02c10BaseSetting) / sizeof(kOv02c10BaseSetting[0]), 0, 0);
    if (ret != kIOReturnSuccess) {
        return ret;
    }

    const UniCamSensorRegVal8 *laneTbl =
        (csiLanes_ == 1U) ? kOv02c10Lane1Setting : kOv02c10Lane2Setting;
    const size_t laneCnt = (csiLanes_ == 1U)
        ? (sizeof(kOv02c10Lane1Setting) / sizeof(kOv02c10Lane1Setting[0]))
        : (sizeof(kOv02c10Lane2Setting) / sizeof(kOv02c10Lane2Setting[0]));
    if ((ret = unicamWriteRegTable8(i2c, "OV02C10", laneTbl, laneCnt, 0, 0)) != kIOReturnSuccess) {
        return ret;
    }

    if ((ret = i2c->writeReg16(kRegVts, static_cast<uint16_t>(activeVts_))) != kIOReturnSuccess) {
        return ret;
    }

    // Default orientation (hflip=0, vflip=0 -> SGRBG10)
    if ((ret = i2c->writeReg16(kRegXWinCtrl, 0x0001U)) != kIOReturnSuccess) return ret;
    if ((ret = i2c->writeReg16(kRegYWinCtrl, 0x0001U)) != kIOReturnSuccess) return ret;
    if ((ret = unicamUpdateRegBits8(i2c, kRegRotateCtrl, 0x18U, 0x08U)) != kIOReturnSuccess) {
        return ret;
    }

    const uint8_t patVal = testPattern
        ? static_cast<uint8_t>(((testPattern - 1U) & 0x03U) | 0x80U)
        : 0x00U;
    if ((ret = i2c->writeReg8(kRegTestPattern, patVal)) != kIOReturnSuccess) {
        return ret;
    }

    return setExposureAndGain(i2c, activeVts_ - kExposureMargin, 256U, kDigitalGainMin);
}

IOReturn OV02C10Driver::setStreaming(II2CTransport *i2c, bool enable) {
    if (!i2c) {
        return kIOReturnBadArgument;
    }
    return i2c->writeReg8(kRegModeSelect, enable ? 0x01 : 0x00);
}

IOReturn OV02C10Driver::setExposureAndGain(II2CTransport *i2c,
                                           uint32_t exposureLines,
                                           uint32_t analogGain,
                                           uint32_t digitalGain) {
    if (!i2c) {
        return kIOReturnBadArgument;
    }

    const uint32_t vts = activeVts_ ? activeVts_ : (kVtsMin * 2U);
    const uint16_t exp = static_cast<uint16_t>(
        unicamClampU32(exposureLines, kExposureMin, vts - kExposureMargin));
    // SoftISP Q8 gain (256=1.0x) -> ov02c10 V4L2 unit (0x10=1.0x) shifted left 4 -> Q8 directly
    const uint32_t gainStep = unicamClampU32(analogGain >> 4, kAnalogGainMin, kAnalogGainMax);
    const uint32_t dGain = unicamClampU32(
        digitalGain < kDigitalGainMin ? kDigitalGainMin : digitalGain,
        kDigitalGainMin, kDigitalGainMax);

    IOReturn ret = i2c->writeReg16(kRegExposure, exp);
    if (ret != kIOReturnSuccess) return ret;

    ret = i2c->writeReg16(kRegAnalogGain, static_cast<uint16_t>(gainStep << 4));
    if (ret != kIOReturnSuccess) return ret;

    return i2c->writeReg24(kRegDigitalGain, dGain << 6);
}
