def main() -> int:
    parser = argparse.ArgumentParser(description="Interactive wizard to create SSDT-CAM / SSDT-CAM-DUMP for UniCam")
    parser.add_argument("--self-test", action="store_true", help="Run non-interactive internal self-test")
    args = parser.parse_args()
    if args.self_test:
        return run_self_test()

    hw = detect_live_hardware()
    has_deploy_tool = os.path.isfile(os.path.join(REPO_ROOT, "tools", "deploy_efi.py"))
    max_opt = 5 if has_deploy_tool else 4
    while True:
        print("\n========================================================================")
        print("  UniCam ACPI Wizard — Pinout Probe & SSDT-CAM Generator")
        print("========================================================================")
        print(f"  System   : PCI Root={hw['pci_root']} | IPU0={'OK' if hw['has_ipu0'] else 'Not found'}"
              f" | CDMP={'Loaded' if hw['has_cdmp'] else 'Not loaded'} | UCAM={'Loaded' if hw['has_ucam'] else 'Not loaded'}")
        print(f"  iasl     : {hw['iasl_bin'] or 'Not found (required when generating/compiling for a new board)'}")
        print("------------------------------------------------------------------------")
        print("  [1] New board (Step 1): Create pinout probe SSDT-CAM-DUMP.aml")
        print("  [2] New board (Step 2): Decode live CDMP pinout -> Generate SSDT-CAM-<Board>.aml")
        print("  [3] Prebuilt board: Copy ready-to-use SSDT-CAM (Dell XPS 7390 2-in-1...)")
        print("  [4] Manual entry: Enter pinout manually -> Generate SSDT-CAM-<Board>.aml")
        if has_deploy_tool:
            print("  [5] Deploy SSDT-CAM & UniCam.kext to OpenCore EFI partition")
        print("  [0] Exit")
        print("------------------------------------------------------------------------")

        choice = prompt_str(f"Select option (0..{max_opt})", "2" if hw["has_cdmp"] else "1")
        if choice == "1":
            action_create_dump(hw)
        elif choice == "2":
            action_generate_from_cdmp(hw)
        elif choice == "3":
            action_use_prebuilt()
        elif choice == "4":
            action_manual_entry(hw)
        elif choice == "5" and has_deploy_tool:
            action_deploy_efi()
        elif choice == "0":
            return 0
        else:
            print(f"[!] Please enter a number between 0 and {max_opt}.")


if __name__ == "__main__":
    raise SystemExit(main())
