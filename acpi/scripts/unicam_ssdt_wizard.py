def compile_dsl_to_aml(dsl_path: str, iasl_bin: str) -> str:
    aml_prefix = os.path.splitext(dsl_path)[0]
    subprocess.run([iasl_bin, "-w2", "-vw", "4089", "-p", aml_prefix, dsl_path], check=True)
    return aml_prefix + ".aml"


def reveal_in_finder(path: str) -> None:
    if sys.stdin.isatty() and not os.environ.get("UNICAM_NONINTERACTIVE"):
        subprocess.run(["open", "-R", path], check=False)


def action_create_dump(hw: dict) -> None:
    os.makedirs(OUTPUT_DIR, exist_ok=True)
    def_dsc = hw["dsc_candidates"][0] if hw["dsc_candidates"] else "DSC1"
    def_lnk = hw["lnk_candidates"][0] if hw["lnk_candidates"] else "LNK2"

    print("\n--- CREATE PINOUT PROBE SSDT-CAM-DUMP.aml ---")
    if hw["dsc_candidates"] or hw["lnk_candidates"]:
        print(f"Auto-detected in ACPI: DSC={hw['dsc_candidates'] or ['(not found)']}, LNK={hw['lnk_candidates'] or ['(not found)']}")

    pci_root = prompt_str("ACPI PCI Root name (PCI0 or PC00)", hw["pci_root"])
    dsc_name = prompt_str("Camera Power Device name (typically DSC1 or DSC0)", def_dsc)
    lnk_name = prompt_str("Camera Sensor Device name (typically LNK2 or LNK0/LNK1)", def_lnk)

    out_dsl = os.path.join(OUTPUT_DIR, "SSDT-CAM-DUMP.dsl")
    out_aml = os.path.join(OUTPUT_DIR, "SSDT-CAM-DUMP.aml")

    if pci_root == "PCI0" and dsc_name == "DSC1" and lnk_name == "LNK2":
        shutil.copy2(os.path.join(ACPI_DIR, "SSDT-CAM-DUMP.dsl"), out_dsl)
        shutil.copy2(os.path.join(ACPI_DIR, "SSDT-CAM-DUMP.aml"), out_aml)
        print(f"\n[+] Copied prebuilt SSDT-CAM-DUMP.aml (PCI0/DSC1/LNK2) to:\n    {out_aml}")
    else:
        iasl_bin = hw["iasl_bin"] or gen_board_ssdt.find_iasl()
        if not iasl_bin:
            print("\n[!] `iasl` compiler is required to build a customized probe SSDT.")
            print("    Please install MaciASL.app into /Applications or run: brew install acpica")
            with open(out_dsl, "w", encoding="utf-8") as f:
                f.write(generate_custom_dump_dsl(pci_root, dsc_name, lnk_name))
            print(f"    Saved DSL source at: {out_dsl}")
            return
        with open(out_dsl, "w", encoding="utf-8") as f:
            f.write(generate_custom_dump_dsl(pci_root, dsc_name, lnk_name))
        compile_dsl_to_aml(out_dsl, iasl_bin)
        print(f"\n[+] Compiled SSDT-CAM-DUMP.aml to:\n    {out_aml}")

    print("\nNext steps:")
    print("  1. Copy SSDT-CAM-DUMP.aml to EFI/OC/ACPI/ and enable it in config.plist -> ACPI -> Add.")
    print("  2. Reboot macOS.")
    print("  3. Re-open this wizard and select [2] to generate SSDT-CAM-<Board>.aml!")
    reveal_in_finder(out_aml)


def slugify_board(raw: str) -> str:
    cleaned = re.sub(r"[^A-Za-z0-9]+", "", raw)
    return cleaned if cleaned else "MyBoard"


def resolve_sensor_preset(raw_hid: str) -> tuple[str, str, int]:
    hid = raw_hid.strip().upper()
    compat, link_hz, _desc = SENSOR_PRESETS.get(hid, ("ovti,ov01a10", 400000000, "Custom"))
    return hid, compat, link_hz


def build_ssdt_from_pinout(data: dict, slug: str, board_id: str, pci_root: str,
                           ipu_name: str, ipu_gen: str, sensor_hid: str,
                           sensor_compat: str, link_freq_hz: int, rotation: int | None,
                           out_dir: str, iasl_bin: str,
                           pmic_type: str = "auto",
                           pmic_i2c_bus: int | None = None,
                           pmic_i2c_addr: int | None = None) -> tuple[str, str]:
    os.makedirs(out_dir, exist_ok=True)
    dsl_path = os.path.join(out_dir, f"SSDT-CAM-{slug}.dsl")
    args = SimpleNamespace(
        board_id=board_id,
        board_slug=slug,
        oem_table_id=f"CAM{slug[:5]}",
        pci_root=pci_root,
        ipu_name=ipu_name,
        ipu_gen=ipu_gen,
        sensor_hid=sensor_hid,
        sensor_compat=sensor_compat,
        link_freq_hz=link_freq_hz,
        rotation=rotation,
        position="front",
        pmic_type=pmic_type,
        pmic_i2c_bus=pmic_i2c_bus,
        pmic_i2c_addr=pmic_i2c_addr,
        pmic_reset_pin=9,
        pmic_pwdn_pin=7,
        pmic_led_pin=0xFF,
    )
    asl_src = gen_board_ssdt.generate_asl(data, args)
    with open(dsl_path, "w", encoding="utf-8") as f:
        f.write(asl_src)

    aml_path = ""
    if iasl_bin:
        aml_path = compile_dsl_to_aml(dsl_path, iasl_bin)
    return dsl_path, aml_path


def action_generate_from_cdmp(hw: dict) -> None:
    print("\n--- DECODE BIOS PINOUT (CDMP) & GENERATE SSDT-CAM ---")
    data = parse_cam_dump.decode_live_cdmp(quiet=False)
    if data is None:
        print("\n[!] Live CDMP pinout data not found. Run option [1], enable SSDT-CAM-DUMP.aml, and Reboot first.")
        return

    iasl_bin = hw["iasl_bin"] or gen_board_ssdt.find_iasl()
    if not iasl_bin:
        print("\n[!] Missing `iasl` compiler (run `brew install acpica` or place `MaciASL.app` in `/Applications`).")
        return

    os.makedirs(OUTPUT_DIR, exist_ok=True)
    json_path = os.path.join(OUTPUT_DIR, "pinout_decoded.json")
    with open(json_path, "w", encoding="utf-8") as jf:
        json.dump(data, jf, indent=2, ensure_ascii=False)

    raw_slug = prompt_str("\nShort board name (e.g. Dell7390, SurfacePro7, YogaC940)", "MyCam")
    slug = slugify_board(raw_slug)
    rot_str = prompt_str("Sensor rotation in degrees (0 or 180, Enter to keep BIOS default)", str(data.get("degree", 0)))
    rotation = int(rot_str) if rot_str.isdigit() else None
    print("\nSupported sensors: OVTI01A0 (OV01A10), OVTI01AB (OV01A1B), INT3474 (OV2740), OVTI02C1 (OV02C10), INT33BE (OV5693), OVTI5675 (OV5675)")
    sensor_hid, sensor_compat, link_freq_hz = resolve_sensor_preset(
        prompt_str("Sensor ACPI HID", "OVTI01A0")
    )

    dsl_path, aml_path = build_ssdt_from_pinout(
        data=data,
        slug=slug,
        board_id=f"custom,{slug.lower()}",
        pci_root=hw["pci_root"],
        ipu_name="IPU0",
        ipu_gen="ipu4p",
        sensor_hid=sensor_hid,
        sensor_compat=sensor_compat,
        link_freq_hz=link_freq_hz,
        rotation=rotation,
        out_dir=OUTPUT_DIR,
        iasl_bin=iasl_bin,
    )

    print(f"\n[+] Saved decoded pinout : {json_path}")
    print(f"[+] Generated SSDT source: {dsl_path}")
    print(f"[+] Compiled AML binary  : {aml_path}")
    print("\nFinal steps:")
    print(f"  1. DISABLE (Enabled=False) SSDT-CAM-DUMP.aml in config.plist.")
    print(f"  2. ENABLE {os.path.basename(aml_path)} in EFI/OC/ACPI/ + UniCam.kext in EFI/OC/Kexts/.")
    print("  3. Reboot macOS and open Photo Booth!")
    reveal_in_finder(aml_path)


def action_use_prebuilt() -> None:
    print("\n--- COPY PREBUILT SSDT-CAM FOR SUPPORTED BOARDS ---")
    boards_dir = os.path.join(ACPI_DIR, "boards")
    amls = sorted(glob.glob(os.path.join(boards_dir, "*", "SSDT-CAM-*.aml")))
    if not amls:
        print("[!] No prebuilt boards found in acpi/boards/.")
        return

    for idx, p in enumerate(amls, start=1):
        board_name = os.path.basename(os.path.dirname(p))
        print(f"  [{idx}] {board_name} -> {os.path.basename(p)}")

    choice = prompt_int("Select board number", 1)
    if choice < 1 or choice > len(amls):
        print("[!] Invalid selection.")
        return

    src_aml = amls[choice - 1]
    src_dsl = os.path.splitext(src_aml)[0] + ".dsl"
    os.makedirs(OUTPUT_DIR, exist_ok=True)
    dst_aml = os.path.join(OUTPUT_DIR, os.path.basename(src_aml))
    shutil.copy2(src_aml, dst_aml)
    if os.path.isfile(src_dsl):
        shutil.copy2(src_dsl, os.path.join(OUTPUT_DIR, os.path.basename(src_dsl)))

    print(f"\n[+] Copied prebuilt SSDT to: {dst_aml}")
    reveal_in_finder(dst_aml)


def resolve_gpio_input(raw: str, sbrg: int = 0xFD000000) -> int:
    raw = raw.strip().upper()
    if raw.startswith("0X"):
        return int(raw, 16)
    m = re.match(r"^(GPP_[A-Z])_(\d+)$", raw)
    if m:
        grp_target, pad_num = m.group(1), int(m.group(2))
        for _gid, (gname, com_off, pad_bar, _base) in parse_cam_dump.ICELAKE_LP_GROUPS.items():
            if gname == grp_target:
                return sbrg + com_off + pad_bar + (pad_num * 0x10)
    raise ValueError(f"Unrecognized GPIO specifier '{raw}' (example: 0xFD6A06F0 or GPP_C_15)")


def prompt_gpio_entry(label: str, func_code: int, default_val: str) -> dict | None:
    while True:
        raw = prompt_str(f"GPIO pin for {label} (pad name e.g. GPP_C_15, hex DW0 0x..., or 'none' to skip)", default_val)
        if raw.lower() in ("none", "0", "skip", "-"):
            return None
        try:
            dw0 = resolve_gpio_input(raw)
        except ValueError as exc:
            print(f"  [!] {exc}")
            continue
        act = prompt_int(f"  Polarity for {label} (1 = Active High, 0 = Active Low)", 1)
        return {
            "group": raw,
            "pad": 0,
            "dw0_addr": dw0,
            "func": func_code,
            "active_high": 1 if act else 0,
        }


def action_manual_entry(hw: dict) -> None:
    print("\n--- MANUAL PINOUT ENTRY & SSDT-CAM GENERATION ---")
    iasl_bin = hw["iasl_bin"] or gen_board_ssdt.find_iasl()
    if not iasl_bin:
        print("[!] Missing `iasl` (install via `brew install acpica` or `MaciASL.app`).")
        return

    slug = slugify_board(prompt_str("Short board name (e.g. Custom7390, SurfacePro7)", "CustomBoard"))
    pci_root = prompt_str("PCI Root (PCI0 or PC00)", hw["pci_root"])
    print("\nSupported sensors: OVTI01A0 (OV01A10), OVTI01AB (OV01A1B), INT3474 (OV2740), OVTI02C1 (OV02C10), INT33BE (OV5693), OVTI5675 (OV5675)")
    sensor_hid, sensor_compat, link_freq_hz = resolve_sensor_preset(
        prompt_str("Sensor ACPI HID", "OVTI01A0")
    )
    pmic_type = prompt_str("Power backend ('discrete' for direct PCH GPIO, 'tps68470' for I2C PMIC)", "discrete").lower()
    use_tps = (pmic_type == "tps68470")

    i2c_bus = prompt_int("Sensor I2C bus index (0..5)", 3)
    i2c_addr = prompt_int("Sensor I2C slave address (hex)", 0x36, base=16)
    mipi_port = prompt_int("MIPI CSI-2 Port index", 6)
    mipi_lanes = prompt_int("MIPI CSI-2 Lanes count (1, 2, 4)", 2 if sensor_hid != "OVTI01A0" else 1)
    mclk_hz = prompt_int("MCLK frequency in Hz (19200000 or 24000000)", 19200000)
    rotation = prompt_int("Sensor rotation in degrees (0 or 180)", 0)

    gpios = []
    pmic_bus = None
    pmic_addr = None
    mclk_src = 1
    mclk_reg = 0xFDAD800C
    if use_tps:
        pmic_bus = prompt_int("TPS68470 PMIC I2C bus index", i2c_bus)
        pmic_addr = prompt_int("TPS68470 PMIC I2C address (hex)", 0x4D, base=16)
    else:
        mclk_src = prompt_int("IMGCLKOUT_x channel index (0..4)", 1)
        mclk_reg = 0xFDAD8000 + (mclk_src * 0x0C)
        for label, code, dflt in (
            ("RESET", 0x00, "GPP_C_15"),
            ("POWER_ENABLE", 0x0B, "GPP_A_21"),
            ("CLK_ENABLE", 0x0C, "GPP_H_20"),
            ("PRIVACY_LED", 0x0D, "GPP_A_11"),
        ):
            g = prompt_gpio_entry(label, code, dflt)
            if g:
                gpios.append(g)

    data = {
        "c1tp": 0 if use_tps else 1,
        "pmic_i2c_bus": pmic_bus or 0,
        "pmic_i2c_addr": pmic_addr or 0,
        "i2c_bus": i2c_bus,
        "i2c_addrs": [{"index": 0, "addr": i2c_addr, "type": 0}],
        "mipi_port": mipi_port,
        "mipi_lanes": mipi_lanes,
        "mclk_hz": mclk_hz,
        "mclk_src": mclk_src,
        "mclk_reg": mclk_reg,
        "degree": rotation,
        "gpios": gpios,
    }
    dsl_path, aml_path = build_ssdt_from_pinout(
        data=data,
        slug=slug,
        board_id=f"manual,{slug.lower()}",
        pci_root=pci_root,
        ipu_name="IPU0",
        ipu_gen="ipu4p",
        sensor_hid=sensor_hid,
        sensor_compat=sensor_compat,
        link_freq_hz=link_freq_hz,
        rotation=rotation,
        out_dir=OUTPUT_DIR,
        iasl_bin=iasl_bin,
        pmic_type="tps68470" if use_tps else "discrete",
        pmic_i2c_bus=pmic_bus,
        pmic_i2c_addr=pmic_addr,
    )
    print(f"\n[+] Generated SSDT source: {dsl_path}")
    print(f"[+] Compiled AML binary  : {aml_path}")
    reveal_in_finder(aml_path)


def action_deploy_efi() -> None:
    print("\n--- DEPLOY SSDT-CAM & UniCam.kext TO OPENCORE EFI ---")
    deploy_py = os.path.join(REPO_ROOT, "tools", "deploy_efi.py")
    prebuilt_kext = os.path.join(REPO_ROOT, "kexts", "UniCam", "build", "UniCam.kext")
    if not os.path.isfile(deploy_py):
        print("[!] tools/deploy_efi.py not found.")
        return
    if not os.path.isdir(prebuilt_kext):
        print("[!] kexts/UniCam/build/UniCam.kext not found. Run kexts/Build-UniCam.command first.")
        return

    out_amls = sorted(glob.glob(os.path.join(OUTPUT_DIR, "SSDT-CAM-*.aml")))
    out_amls = [p for p in out_amls if not p.endswith("SSDT-CAM-DUMP.aml")]
    default_aml = out_amls[0] if out_amls else os.path.join(
        ACPI_DIR, "boards", "dell-xps-7390-2in1", "SSDT-CAM-Dell7390.aml"
    )
    aml_path = prompt_str("Path to SSDT-CAM-*.aml to deploy", default_aml)
    if not os.path.isfile(aml_path):
        print(f"[!] File not found: {aml_path}")
        return

    cmd = [sys.executable, deploy_py, "--aml", aml_path, "--kext", prebuilt_kext]
    print(f"[*] Running: {' '.join(cmd)}")
    res = subprocess.run(cmd)
    if res.returncode != 0:
        print("\n[i] If the EFI partition is not mounted, mount it first and re-run (or run with sudo).")


