def run_cmd(args: list[str]) -> str:
    try:
        return subprocess.check_output(args, stderr=subprocess.DEVNULL).decode("utf-8", "replace")
    except Exception:
        return ""


def detect_live_hardware() -> dict:
    acpi_dump = run_cmd(["ioreg", "-p", "IOACPIPlane", "-r", "-d", "4"])
    pci_root = "PC00" if "+-o PC00@" in acpi_dump else "PCI0"

    dsc_matches = re.findall(r"\+-o (DSC[0-9A-Z])@", acpi_dump)
    lnk_matches = re.findall(r"\+-o (LNK[0-9A-Z])@", acpi_dump)
    has_cdmp = "+-o CDMP@" in acpi_dump
    has_ucam = "+-o UCAM@" in acpi_dump
    has_ipu0 = bool(re.search(r"\+-o IPU0@", acpi_dump)) or ("8a19" in run_cmd(["ioreg", "-r", "-n", "IPU0", "-d", "1"]))

    return {
        "pci_root": pci_root,
        "dsc_candidates": sorted(set(dsc_matches)),
        "lnk_candidates": sorted(set(lnk_matches)),
        "has_cdmp": has_cdmp,
        "has_ucam": has_ucam,
        "has_ipu0": has_ipu0,
        "iasl_bin": gen_board_ssdt.find_iasl(),
    }


def prompt_str(msg: str, default: str = "") -> str:
    suffix = f" [{default}]" if default else ""
    try:
        val = input(f"{msg}{suffix}: ").strip()
    except EOFError:
        return default
    return val if val else default


def prompt_int(msg: str, default: int, base: int = 0) -> int:
    while True:
        raw = prompt_str(msg, f"0x{default:X}" if base == 16 else str(default))
        try:
            return int(raw, 16 if base == 16 else 0)
        except ValueError:
            print(f"  [!] Invalid number format '{raw}', please try again.")


